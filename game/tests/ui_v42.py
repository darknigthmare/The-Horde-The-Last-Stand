from pathlib import Path
import json,re,hashlib
R=Path(__file__).resolve().parents[1]
H=(R/'JOUER_DERNIERE_LIGNE.html').read_text(encoding='utf-8',errors='ignore')
CSS=(R/'src/ui_v42.css').read_text(encoding='utf-8')
JS=(R/'src/ui_v42.js').read_text(encoding='utf-8')
checks=[]
def check(name,ok,detail=None):
    checks.append({'test':name,'ok':bool(ok),'detail':detail})
    print(('OK ' if ok else 'FAIL ')+name)
check('Titre 0.42.0', 'Poste de commandement 0.42.0' in H)
check('CSS dédié injecté une seule fois', H.count('id="dl42-ui-style"')==1)
check('JS dédié injecté une seule fois', H.count('id="dl42-ui-script"')==1)
check('Classe UI installée à l’exécution', "classList.add('dl42-ui')" in JS)
check('Boot cinématique local', "id='dl42Boot'" in JS and '#dl42Boot' in CSS)
check('Transition de scène', 'dl42SceneWipe' in JS and '@keyframes dl42wipe' in CSS)
check('Plein écran natif', 'requestFullscreen' in JS and 'exitFullscreen' in JS)
check('Raccourci F10', "e.code==='F10'" in JS)
check('Bouton plein écran HUD', 'dl42FullscreenBtn' in JS)
check('Bouton plein écran menu', 'dl42FullscreenMenu' in JS)
check('Légende clavier/manette', 'dl42ControlLegend' in JS and 'data-pad' in JS and 'data-kb' in JS)
check('Navigation visuelle focus', 'dl42-focus-ring' in CSS and 'focusin' in JS)
check('HUD tactique caméra', 'dl42TacticalLine' in JS and 'currentView' in JS)
check('Compteur contacts sans modifier les ennemis', 'dl42Contacts' in JS and '.filter(z=>z&&!z.dead).length' in JS)
check('Menu traité comme poste de commandement', '#menuScreen[data-dl403] .menu-command' in CSS)
check('Hub menu retravaillé', '#dl403-hubNav' in CSS)
check('Préparation retravaillée', '.camp-wrap' in CSS and '.camp-heading' in CSS)
check('Rail de sections retravaillé', '.tabs button.selected' in CSS and '#dl403-groupnav' in CSS)
check('Cartes retravaillées', '.game-card' in CSS and 'clip-path' in CSS)
check('Renseignements retravaillés', '.intel' in CSS)
check('Dialogues briefing', '.dialog:before' in CSS)
check('HUD combat retravaillé', '#weaponReadout' in CSS and '#actions button' in CSS)
check('Boss HUD retravaillé', '#bossPanel' in CSS)
check('Rythme de horde retravaillé', '#v22PressurePanel' in CSS and '#v22BreatherPanel' in CSS)
check('Stand de tir retravaillé', '#practiceBar' in CSS)
check('Formulaires non natifs', 'input[type=checkbox]' in CSS and 'select{appearance:none' in CSS)
check('Détails et tableaux cohérents', 'details[open]>summary' in CSS and '#shell.dl42-ui table' in CSS)
check('Responsive tablette', '@media(max-width:1180px)' in CSS)
check('Responsive mobile', '@media(max-width:760px)' in CSS)
check('Mode paysage court', '@media(max-height:580px)' in CSS)
check('Reduced motion', 'prefers-reduced-motion:reduce' in CSS)
check('Aucun accès réseau dans la couche UI', not re.search(r'\b(fetch|XMLHttpRequest|WebSocket|EventSource)\b',JS))
for forbidden in ['run.cash=','ENEMIES[','damage=','dmg=','wave.list','totalSpent+=','hitZombie=function','fireGun=function']:
    check('UI sans règle gameplay · '+forbidden, forbidden not in JS)
check('Build reproductible référence CSS', "read('src/ui_v42.css')" in (R/'build.mjs').read_text())
check('Build reproductible référence JS', "read('src/ui_v42.js')" in (R/'build.mjs').read_text())
passed=sum(x['ok'] for x in checks)
out={'version':'0.42.0','passed':passed,'total':len(checks),'failed':[x for x in checks if not x['ok']], 'sha256':{'css':hashlib.sha256(CSS.encode()).hexdigest(),'js':hashlib.sha256(JS.encode()).hexdigest()}}
(R/'rapports/UI_0_42_0_QA.json').write_text(json.dumps(out,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'passed':passed,'total':len(checks),'failed':len(out['failed'])},ensure_ascii=False))
raise SystemExit(0 if passed==len(checks) else 1)
