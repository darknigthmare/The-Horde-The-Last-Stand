from pathlib import Path
import json,re,hashlib,sys
R=Path(__file__).resolve().parents[1]
H=(R/'JOUER_DERNIERE_LIGNE.html').read_text(encoding='utf-8',errors='ignore')
CSS=(R/'src/ui_v43.css').read_text(encoding='utf-8')
JS=(R/'src/ui_v43.js').read_text(encoding='utf-8')
BUILD=(R/'build.mjs').read_text(encoding='utf-8')
checks=[]
def check(name,ok,detail=None):
    checks.append({'test':name,'ok':bool(ok),'detail':detail})
    print(('OK ' if ok else 'FAIL ')+name)
check('Titre 0.43.0', 'Clarté de terrain 0.43.0' in H)
check('CSS v43 injecté une fois', H.count('id="dl43-ui-style"')==1)
check('JS v43 injecté une fois', H.count('id="dl43-ui-script"')==1)
check('Couche v42 conservée', H.count('id="dl42-ui-style"')==1 and H.count('id="dl42-ui-script"')==1)
check('Classe v43 progressive', "classList.add('dl43-ui')" in JS)
check('Mode détails contextuel', 'dl43-details-open' in JS and 'dl43DetailsBtn' in JS)
check('Renseignements en tiroir', 'dl43-intel-open' in JS and 'dl43IntelBtn' in JS)
check('Tiroir protégé des rerenders legacy', "style.setProperty('visibility','visible','important')" in JS)
check('Informations profondes masquées en essentiel', '.dl43-deep{display:none!important}' in CSS)
check('Textes longs limités en essentiel', '-webkit-line-clamp:2' in CSS)
check('Navigation camp horizontale', '#shell.dl43-ui .tabs{grid-row:2' in CSS and 'display:flex!important' in CSS and 'overflow-x:auto!important' in CSS)
check('Renseignements ne sont plus une colonne permanente', '.intel{position:absolute!important' in CSS)
check('Bande de contexte de section', 'dl43SectionBand' in JS and '#dl43SectionBand' in CSS)
check('Comptage actions de section', 'dl43SectionCount' in JS)
check('Réglages repliables', 'dl43-settings-fold' in JS and '.dl43-settings-fold' in CSS)
check('Réglages legacy regroupés', 'dl43-settings-general' in JS and 'dl43-settings-cluster' in CSS)
check('Une catégorie générale ouverte par défaut', "details.open=true" in JS)
check('HUD actions groupées', 'dl43WeaponActions' in JS and 'dl43UtilityActions' in JS)
check('Labels action au survol/focus', '.dl43-action-label' in CSS and ':focus-visible .dl43-action-label' in CSS)
check('Marque HUD masquée au combat', '[data-phase="combat"] #hud .brand' in CSS)
check('Crédits masqués au combat', '.hudstat.cash' in CSS)
check('Statut arme contextuel', 'dl43-critical' in JS and '#weaponReadout .label.dl43-critical' in CSS)
check('Objectif compact', 'compactObjective' in JS)
check('Objectif secondaire vide supprimé', 'dl43-silent' in JS and 'AUCUN(?:E)?\\s+OBJECTIF' in JS)
check('États absents supprimés', 'dl43-muted-state' in JS and 'ABSENTE' in JS)
check('Pression calme supprimée', 'dl43-passive' in JS and '#v22PressurePanel.dl43-passive' in CSS)
check('Actions tactiques indisponibles supprimées', '#tacticalActions button:disabled{display:none!important}' in CSS)
check('Aide combat permanente supprimée', '#combatTip{display:none!important}' in CSS)
check('Build arme combat masqué', '#v36-combat-build{display:none!important}' in CSS)
check('Boutons HUD compacts', '#actions button{width:43px!important' in CSS)
check('Responsive tablette', '@media(max-width:980px)' in CSS)
check('Responsive mobile', '@media(max-width:720px)' in CSS)
check('Paysage court', '@media(max-height:600px)' in CSS)
check('Reduced motion', 'prefers-reduced-motion:reduce' in CSS)
check('Aucun réseau dans la couche v43', not re.search(r'\b(fetch|XMLHttpRequest|WebSocket|EventSource)\b',JS))
for forbidden in ['run.cash=','ENEMIES[','damage=','dmg=','wave.list','totalSpent+=','hitZombie=function','fireGun=function']:
    check('UI v43 sans règle gameplay · '+forbidden, forbidden not in JS)
check('Build reproductible CSS v43', "read('src/ui_v43.css')" in BUILD)
check('Build reproductible JS v43', "read('src/ui_v43.js')" in BUILD)
passed=sum(x['ok'] for x in checks)
out={'version':'0.43.0','passed':passed,'total':len(checks),'failed':[x for x in checks if not x['ok']], 'sha256':{'css':hashlib.sha256(CSS.encode()).hexdigest(),'js':hashlib.sha256(JS.encode()).hexdigest()}}
(R/'rapports/UI_0_43_0_QA.json').write_text(json.dumps(out,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'passed':passed,'total':len(checks),'failed':len(out['failed'])},ensure_ascii=False))
sys.exit(0 if passed==len(checks) else 1)
